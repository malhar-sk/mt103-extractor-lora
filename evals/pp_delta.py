"""What postprocess.py changes, per run: field values fixed (wrong -> right) and broken (right -> wrong).

Reads cached raw model outputs only (no model calls) and writes results/postprocess_delta.md.

    python evals/pp_delta.py
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from evals.run_eval import SCORED_FIELDS, score_one  # noqa: E402
from postprocess import postprocess  # noqa: E402
from prompts import parse_output  # noqa: E402

RUNS = [("data/test.jsonl", "base-qwen2.5-0.5b-fewshot"), ("data/test.jsonl", "ft-qwen2.5-0.5b-lora"),
        ("data/test.jsonl", "api-claude-haiku-5-5-fewshot"),
        ("data/ood_test.jsonl", "ood-base-qwen2.5-0.5b-fewshot"), ("data/ood_test.jsonl", "ood-ft-qwen2.5-0.5b-lora"),
        ("data/ood_test.jsonl", "ood-api-claude-haiku-5-5-fewshot")]


def delta(data_path: Path, cache_path: Path):
    rows = [json.loads(x) for x in open(data_path, encoding="utf-8") if x.strip()]
    raw = {}
    for line in open(cache_path, encoding="utf-8"):
        r = json.loads(line)
        raw[r["id"]] = r.get("raw")
    fixed, broke = collections.Counter(), collections.Counter()
    for ex in rows:
        obj = parse_output(raw.get(ex["id"]))
        a = score_one(ex["target"], obj)["fields"]
        b = score_one(ex["target"], postprocess(obj, ex["text"]))["fields"]
        for k in SCORED_FIELDS:
            fixed[k] += (not a[k]) and b[k]
            broke[k] += a[k] and (not b[k])
    return len(rows), fixed, broke


def main():
    lines = ["# What the deterministic post-processing changes", "",
             "Generated by `python evals/pp_delta.py` from cached raw outputs (no model calls). "
             "*Fixed* = field values that were wrong and are right after `postprocess.py`; "
             "*broken* = right before and wrong after.", "",
             "| Run | n | Field values fixed | Field values broken | Most fixed fields |", "|---|---|---|---|---|"]
    for data, name in RUNS:
        cp = ROOT / "results" / "cache" / f"{name}.jsonl"
        if not cp.exists():
            continue
        n, fixed, broke = delta(ROOT / data, cp)
        top = ", ".join(f"{k} {v}" for k, v in fixed.most_common(4) if v)
        lines.append(f"| {name} | {n} | {sum(fixed.values())} | {sum(broke.values())} | {top} |")
    out = ROOT / "results" / "postprocess_delta.md"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
